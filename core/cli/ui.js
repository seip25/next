const ALIASES = {
  snackbar: "toast",
  toasts: "toast",
  confirm: "provider",
  dialog: "modal",
  sheet: "drawer",
  table: "datatable",
  "data-table": "datatable",
  textarea: "input",
  field: "input",
  switch: "checkbox",
  radio: "checkbox",
  upload: "file-upload",
  dropzone: "file-upload",
  menu: "dropdown",
  emptystate: "empty-state",
  empty: "empty-state",
};

function resolve(names) {
  const out = new Set();
  const visit = (name) => {
    const key = ALIASES[name] || name;
    const entry = UI_COMPONENTS[key];
    if (!entry) throw new Error(`Componente desconocido: '${name}'. Usa 'make:ui --list' para ver la lista.`);
    if (out.has(key)) return;
    entry.deps.forEach(visit);
    out.add(key);
  };
  names.forEach(visit);
  return [...out];
}

function readJson(file) {
  try {
    return JSON.parse(fs.readFileSync(file, "utf8"));
  } catch {
    return null;
  }
}

function findGlobalCss(cwd) {
  const candidates = ["src/app/globals.css", "app/globals.css", "src/styles/globals.css", "styles/globals.css"];
  return candidates.map((c) => path.join(cwd, c)).find((f) => fs.existsSync(f)) || null;
}

/** Rewrites <dir>/index.js so it only re-exports the components present in the folder. */
function writeBarrel(targetDir) {
  const lines = ["// Barrel: import { Button, Input, DataTable } from \"@/ui\";", "// Regenerated by `npx seip make:ui`."];
  for (const [, entry] of Object.entries(UI_COMPONENTS)) {
    if (fs.existsSync(path.join(targetDir, entry.file))) {
      lines.push(`export * from "./${entry.file.replace(/\.(jsx?|tsx?)$/, "")}";`);
    }
  }
  fs.writeFileSync(path.join(targetDir, "index.js"), lines.join("\n") + "\n", "utf8");
}

/**
 * Copies UI components (Tailwind v4) into the project so they can be edited freely.
 * @param {string[]} names Components to copy (empty = all).
 * @param {{dir?: string, force?: boolean, list?: boolean, cwd?: string, silent?: boolean}} [options]
 * @returns {{dir: string, copied: string[], skipped: string[]}}
 */
export function makeUi(names = [], options = {}) {
  const cwd = options.cwd || process.cwd();
  const log = options.silent ? () => {} : console.log;

  if (options.list) {
    log(colors.bold("\nComponentes disponibles (npx seip make:ui <nombre> [...]):\n"));
    for (const [name, entry] of Object.entries(UI_COMPONENTS)) {
      if (name === "utils") continue;
      log(`  ${colors.green(name.padEnd(13))} ${entry.client ? colors.yellow("client") : colors.cyan("server")}  ${colors.gray(entry.description)}`);
    }
    log(colors.gray(`\n  Alias: ${Object.keys(ALIASES).join(", ")}\n`));
    return { dir: null, copied: [], skipped: [] };
  }

  const targetDir = path.resolve(cwd, options.dir || (fs.existsSync(path.join(cwd, "src")) ? "src/ui" : "ui"));
  const keys = resolve(names.length ? names : Object.keys(UI_COMPONENTS));
  fs.mkdirSync(targetDir, { recursive: true });

  const copied = [];
  const skipped = [];
  const files = ["theme.css", ...keys.map((k) => UI_COMPONENTS[k].file)];
  for (const file of files) {
    const dest = path.join(targetDir, file);
    if (fs.existsSync(dest) && !options.force) {
      skipped.push(file);
      continue;
    }
    fs.copyFileSync(path.join(TEMPLATE_DIR, file), dest);
    copied.push(file);
  }
  writeBarrel(targetDir);

  const rel = path.relative(cwd, targetDir) || ".";
  log(colors.bold.green(`\n[OK] UI en ./${rel}/`));
  if (copied.length) log(colors.gray(`  Copiados: ${copied.join(", ")}`));
  if (skipped.length) log(colors.yellow(`  Ya existían (no se tocaron, usa --force para reemplazar): ${skipped.join(", ")}`));

  // Tailwind v4 checks
  const pkg = readJson(path.join(cwd, "package.json")) || {};
  const deps = { ...pkg.dependencies, ...pkg.devDependencies };
  const twVersion = deps.tailwindcss;
  if (!twVersion) {
    log(colors.yellow("\n[!] Tailwind CSS no está instalado. Instálalo (v4):"));
    log(colors.white("    npm install -D tailwindcss @tailwindcss/postcss"));
  } else if (/^[~^]?[0-3]\./.test(twVersion)) {
    log(colors.yellow(`\n[!] Tienes tailwindcss ${twVersion}. Estos componentes usan Tailwind v4: npx @tailwindcss/upgrade`));
  }
  const postcss = ["postcss.config.mjs", "postcss.config.js", "postcss.config.cjs"].find((f) => fs.existsSync(path.join(cwd, f)));
  if (!postcss) {
    fs.writeFileSync(
      path.join(cwd, "postcss.config.mjs"),
      'export default {\n  plugins: { "@tailwindcss/postcss": {} },\n};\n',
      "utf8"
    );
    log(colors.gray("  Creado postcss.config.mjs con @tailwindcss/postcss"));
  }

  // Import theme.css in the global stylesheet
  const globalCss = findGlobalCss(cwd);
  if (globalCss) {
    let css = fs.readFileSync(globalCss, "utf8");
    let themeRel = path.relative(path.dirname(globalCss), path.join(targetDir, "theme.css")).split(path.sep).join("/");
    if (!themeRel.startsWith(".")) themeRel = `./${themeRel}`;
    if (!css.includes("theme.css")) {
      const importLine = `@import "${themeRel}";`;
      if (/@import\s+["']tailwindcss["'];?/.test(css)) {
        css = css.replace(/(@import\s+["']tailwindcss["'];?)/, `$1\n${importLine}`);
      } else {
        css = `@import "tailwindcss";\n${importLine}\n\n${css}`;
      }
      fs.writeFileSync(globalCss, css, "utf8");
      log(colors.gray(`  ${path.relative(cwd, globalCss)}: agregado ${importLine}`));
    }
  } else {
    log(colors.yellow("\n[!] No encontré globals.css. En tu CSS global agrega:"));
    log(colors.white(`    @import "tailwindcss";\n    @import "<ruta>/${path.basename(targetDir)}/theme.css";`));
  }

  log(colors.bold("\nSiguientes pasos:"));
  if (keys.includes("provider") || keys.includes("toast")) {
    log(colors.white("  1. En app/layout.js envuelve la app:"));
    log(colors.gray('       import { UIProvider } from "@/ui/provider";'));
    log(colors.gray("       <body><UIProvider>{children}</UIProvider></body>"));
  }
  log(colors.white('  2. Importa: import { Button, Input, DataTable } from "@/ui";'));
  log(colors.gray("     (el alias @/* viene en create-next-app; si no lo tienes usa rutas relativas)"));
  log(colors.white("  3. Los archivos son tuyos: edítalos. Cambia colores en theme.css (--ui-primary, ...).\n"));

  return { dir: targetDir, copied, skipped };
}

export default makeUi;
